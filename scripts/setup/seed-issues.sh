- [ ] API のテストで確かめる。README の API 表を更新する
- [ ] \`pnpm check\` が通る

### 触ってよい範囲 / 触ってはいけない範囲
触ってよい: packages/shared、apps/api、README.md
触ってはいけない: DB スキーマ（インデックスの追加は別の Issue）

### 任せるレベル
