#!/bin/bash
# 追体験用の Issue を作る（リポジトリを作った人が1回だけ実行する）
# 仕様がはっきりしたもの・あいまいなもの・危ないもの・ずれの洗い出し、を混ぜてある。すべて triage（仕分け待ち）で作る
# usage: scripts/setup/seed-issues.sh [owner/repo]
set -euo pipefail
REPO=${1:-$(gh repo view --json nameWithOwner -q .nameWithOwner)}
issue() { gh issue create --repo "$REPO" --title "$1" --label "triage,$2" --body "$3" >/dev/null && echo "✔ $1"; }

issue "投票の取り消しで、票が減りすぎる" "type:bug" "### 背景・何に困っているか
投票していない人が「取り消し」を送ると、票の数が減ってしまう。0 より小さくなることもある。

### 完了条件（機械で確かめられる形で）
- [ ] 投票していない人が取り消しても、票の数は変わらない（API のテストで確かめる）
- [ ] 投票した人が取り消すと、票が1つ減る（既存のテストが通り続ける）
- [ ] \`pnpm check\` が通る

### 触ってよい範囲 / 触ってはいけない範囲
触ってよい: apps/api/src/services/votes.ts、apps/api/test/
触ってはいけない: DB スキーマ

### 任せるレベル
修正案の PR（検証を通した PR まで。マージは人）"

